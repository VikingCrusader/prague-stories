const LanguageContext = createContext(null);

// BCP 47 codes for <html lang>, so the browser hyphenates with the right
// dictionary (Czech is "cs", not the app's own "cz" key).
const HTML_LANG = { en: 'en', cz: 'cs', zh: 'zh' };

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('lang') || 'en';
    document.documentElement.setAttribute('data-lang', saved);
    document.documentElement.setAttribute('lang', HTML_LANG[saved] || 'en');
    return saved;
  });
  const [zhVariant, setZhVariant] = useState(() => {
    const saved = localStorage.getItem('zhVariant') || 'cn';
    // Lets CSS pick fonts per script (e.g. a Simplified-only title font).
    document.documentElement.setAttribute('data-zh-variant', saved);
    return saved;
  });

  const changeLang = (l) => {
    setLang(l);
    localStorage.setItem('lang', l);
    document.documentElement.setAttribute('data-lang', l);
    document.documentElement.setAttribute('lang', HTML_LANG[l] || 'en');
  };

  const changeZhVariant = (v) => {
    setZhVariant(v);
    localStorage.setItem('zhVariant', v);
    document.documentElement.setAttribute('data-zh-variant', v);
  };

  return (
    <LanguageContext.Provider value={{ lang, changeLang, zhVariant, changeZhVariant }}>
      {children}
    </LanguageContext.Provider>
  );
}

// Renders `children` as if the app language were `lang`, leaving the rest of
// the context (zhVariant, changeLang) intact. Used where content arrives in
// one language only and must keep rendering in that language until the
// payload for a newly chosen language has loaded (see HistoryPage).
export function LanguageOverride({ lang, children }) {
  const ctx = useContext(LanguageContext);
  return (
    <LanguageContext.Provider value={{ ...ctx, lang: lang ?? ctx.lang }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  return useContext(LanguageContext);
}

export function useConvert() {
  const { lang, zhVariant } = useLang();
  return (str) => {
    if (lang === 'zh' && zhVariant === 'tw' && str) return toTW(str);
    return str;
  };
}

export function useT() {
  const { lang, zhVariant } = useLang();
  return (key, vars) => {
    let str = (T[lang] && T[lang][key] !== undefined ? T[lang][key] : T.en[key]) ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace('{' + k + '}', v);
      });
    }
    if (lang === 'zh' && zhVariant === 'tw') str = toTW(str);
    return str;
  };
}
